#!/usr/bin/env python3
"""Probe the prefix-closed language not killed by a uniform inverse rewrite.

The source language is generated by the record atoms

    A = 1, B = 12, C = 1113, D = 1122.

For an exact source word w of raw length L, a *uniform rewrite* is an
alternative exact word v of length at most L which reaches the same endpoint
from a smaller start at the least source representative and whose cylinder
lift is strictly smaller than the source cylinder lift.  Cylinder transport
then makes the descent valid on every source lift and after every common
suffix.

The probe grows only prefixes over A,B,D which have not already been killed.
At each live prefix R it also tests R C.  Thus it directly measures the
finite-state hope that every first occurrence of C is eventually covered by
a uniform rewrite.  This is a discovery probe, not an all-depth proof.
"""

from argparse import ArgumentParser
from collections import Counter, defaultdict

from rewrite_discovery_probe import (
    ATOMS,
    canonical_seed_and_endpoint,
    reverse_exponents,
    word_text,
)


PREFIX_ATOMS = ("A", "B", "D")


def uniform_witness(endpoint, seed, source_word):
    """Return a same-or-shorter cylinder-contracting predecessor, if found."""
    source_depth = len(source_word)
    source_mass = sum(source_word)
    states = {endpoint: ()}

    for depth in range(1, source_depth + 1):
        remaining = source_depth - depth
        largest_live_state = (
            3**remaining * (seed + 1) - 1
        ) // 2**remaining - 1
        next_states = {}

        for target, suffix in states.items():
            for exponent, predecessor in reverse_exponents(target):
                if predecessor > largest_live_state:
                    break
                if predecessor <= 0:
                    continue

                alternative = (exponent,) + suffix
                alternative_mass = sum(alternative)
                lift_left = 2**alternative_mass * 3 ** (source_depth - depth)
                lift_right = 2**source_mass
                if predecessor < seed and lift_left < lift_right:
                    return predecessor, alternative, lift_left, lift_right

                if predecessor % 3 != 0 and predecessor not in next_states:
                    next_states[predecessor] = alternative

        states = next_states
        if not states:
            break

    return None


def data_for(names):
    word = tuple(value for name in names for value in ATOMS[name])
    seed, endpoint = canonical_seed_and_endpoint(word)
    return word, seed, endpoint


def main():
    parser = ArgumentParser()
    parser.add_argument("--max-atoms", type=int, default=9)
    parser.add_argument("--max-raw-depth", type=int, default=28)
    parser.add_argument("--samples", type=int, default=20)
    args = parser.parse_args()

    live = [()]
    totals = Counter()
    first_c_survivors = defaultdict(list)
    first_c_killed = defaultdict(list)
    live_samples = defaultdict(list)
    c_suffixes = defaultdict(Counter)

    for atom_depth in range(args.max_atoms + 1):
        next_live = []
        for names in live:
            if names:
                word, seed, endpoint = data_for(names)
                if uniform_witness(endpoint, seed, word) is not None:
                    totals[(atom_depth, "prefix_killed")] += 1
                    continue
                totals[(atom_depth, "prefix_live")] += 1
                if len(live_samples[atom_depth]) < args.samples:
                    live_samples[atom_depth].append(("".join(names), seed))

            c_names = names + ("C",)
            c_word, c_seed, c_endpoint = data_for(c_names)
            if len(c_word) <= args.max_raw_depth:
                witness = uniform_witness(c_endpoint, c_seed, c_word)
                if witness is None:
                    totals[(atom_depth, "first_c_live")] += 1
                    if len(first_c_survivors[atom_depth]) < args.samples:
                        first_c_survivors[atom_depth].append(
                            ("".join(c_names), c_seed, c_endpoint)
                        )
                    for width in range(1, min(5, len(names)) + 1):
                        c_suffixes[(atom_depth, width)]["".join(names[-width:])] += 1
                else:
                    totals[(atom_depth, "first_c_killed")] += 1
                    if len(first_c_killed[atom_depth]) < args.samples:
                        predecessor, alternative, lift_left, lift_right = witness
                        first_c_killed[atom_depth].append(
                            (
                                "".join(c_names),
                                word_text(alternative),
                                predecessor,
                                f"{lift_left}/{lift_right}",
                            )
                        )

            if atom_depth == args.max_atoms:
                continue
            for name in PREFIX_ATOMS:
                extended = names + (name,)
                raw_depth = sum(len(ATOMS[item]) for item in extended)
                if raw_depth <= args.max_raw_depth:
                    next_live.append(extended)
        live = next_live

    for atom_depth in range(args.max_atoms + 1):
        print(
            f"atom_depth={atom_depth} "
            f"prefix_live={totals[(atom_depth, 'prefix_live')]} "
            f"prefix_killed={totals[(atom_depth, 'prefix_killed')]} "
            f"first_C_live={totals[(atom_depth, 'first_c_live')]} "
            f"first_C_killed={totals[(atom_depth, 'first_c_killed')]}"
        )
        if live_samples[atom_depth]:
            print("  live_prefix_samples=" + repr(live_samples[atom_depth]))
        if first_c_survivors[atom_depth]:
            print(
                "  first_C_survivor_samples="
                + repr(first_c_survivors[atom_depth])
            )
        if first_c_killed[atom_depth]:
            print(
                "  first_C_killed_samples="
                + repr(first_c_killed[atom_depth])
            )
        for width in range(1, 6):
            counts = c_suffixes.get((atom_depth, width))
            if counts:
                print(
                    f"  survivor_suffix_width_{width}="
                    + repr(counts.most_common(12))
                )

    print("UNIFORM REWRITE SURVIVOR PROBE COMPLETE")


if __name__ == "__main__":
    main()
